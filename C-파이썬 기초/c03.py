temp_f=100 #화씨온도 선언
temp_c=(temp_f-37)*5//9 #섭씨온도 선언과 화씨와의 관계식
print("화씨온도에서 37을 뺀 뒤, 5/9를 곱하면 섭씨온도가 된다.") #계산과정 설명
print(temp_f,"F") #화씨온도 출력
print(temp_c,"C") #섭씨온도 출력

print("") #줄 띄움

time=127 #전체시간 선언
print("전체시간(초):",time) #전체시간 출력
print(time//60,"분") #전체시간에서 몇 분인지 계산
print(time%60,"초") #전체시간에서 몇 초인지 계산
#섭씨, 화씨온도 관계식과 전체 초를 분으로 환산하는 식